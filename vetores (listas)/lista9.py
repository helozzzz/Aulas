numeros = [3, 1, 4, 2]
numeros.sort()
print(numeros) # [1, 2, 3, 4]

nomes = ["carlos", "ana", "bruno"]
nomes.sort()
print(nomes) # ["ana", "bruno", "carlos"]

numeros = [3, 1, 4, 2]
numeros.sort(reverse=True)
print(numeros) # [4, 3, 2, 1]

nomes = ["carlos", "ana", "bruno"]
nomes.sort(reverse=True)
print(nomes) # ["carlos", "bruno", "ana"]